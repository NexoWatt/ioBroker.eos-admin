/** Retires legacy UI caches and worker ownership for the unified authenticated origin.
 * Protected pages and API responses are always obtained from the owner server. */
self.addEventListener('install', event => event.waitUntil(self.skipWaiting()));
self.addEventListener('activate', event => {
  event.waitUntil((async () => {
    const keys = await caches.keys();
    await Promise.all(keys.filter(key => key.startsWith('nexowatt-cache-')).map(key => caches.delete(key)));
    await self.clients.claim();
    await self.registration.unregister();
  })());
});
// Deliberately no fetch interception or offline protected application cache.
